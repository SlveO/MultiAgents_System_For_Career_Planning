from __future__ import annotations

import math
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

try:
    from project.core.schemas import EvidenceItem, PerceptionResult
except ImportError:
    from core.schemas import EvidenceItem, PerceptionResult

from .base import _extract_facts_fallback, _safe_confidence


@dataclass
class _DocumentContent:
    # Blocks retain original document locations, including PDF page numbers.
    blocks: list[tuple[str, str, str]] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    requires_confirmation: bool = False


class DocumentPerceptionAgent:
    """Bounded extraction; scanned PDF vision requires an injected local agent."""

    MAX_FILE_BYTES = 25 * 1024 * 1024
    MAX_PDF_PAGES = 10
    MAX_SHEETS = 3
    MAX_ROWS = 20
    MAX_COLUMNS = 12
    MAX_RENDER_PIXELS = 4_000_000
    MAX_RENDER_SIDE = 2400

    def __init__(self, *, max_text_chars: int = 3000):
        if max_text_chars < 1:
            raise ValueError("Document text budget must be positive")
        self.max_text_chars = max_text_chars

    def _read_txt(self, path: Path) -> _DocumentContent:
        with path.open(encoding="utf-8", errors="ignore") as handle:
            text = handle.read(self.max_text_chars + 1)
        return _DocumentContent(blocks=[(str(path), "", text)])

    def _read_pdf(self, path: Path, image_agent=None) -> _DocumentContent:
        from pypdf import PdfReader

        content = _DocumentContent()
        reader = PdfReader(str(path))
        if len(reader.pages) > self.MAX_PDF_PAGES:
            content.warnings.append(f"PDF truncated: only the first {self.MAX_PDF_PAGES} pages were read")
        used_chars = 0
        for index, page in enumerate(reader.pages[:self.MAX_PDF_PAGES]):
            number = index + 1
            text = (page.extract_text() or "").strip()
            if not text:
                if image_agent is None:
                    content.warnings.append(
                        f"PDF page {number} has no extractable text; use --scan-pdf with local vision to inspect it"
                    )
                    continue
                try:
                    text = self._read_scanned_page(path, index, image_agent)
                except ImportError:
                    content.warnings.append(
                        f"PDF page {number} vision unavailable: optional pypdfium2/Pillow or PyMuPDF renderer is not installed"
                    )
                    continue
                except Exception as exc:
                    content.warnings.append(f"PDF page {number} vision failed ({type(exc).__name__})")
                    continue
                if not text.strip():
                    content.warnings.append(f"PDF page {number} vision returned no usable content")
                    continue
                content.requires_confirmation = True
                content.warnings.append(
                    f"PDF page {number} text was generated by local vision and requires source verification"
                )
            content.blocks.append((f"{path}#page={number}", f"[page {number}]", text))
            used_chars += len(text)
            if used_chars > self.max_text_chars:
                break
        return content

    def _read_scanned_page(self, path: Path, index: int, image_agent) -> str:
        # Official pypdfium2 support-model API: render -> bitmap -> PIL image.
        # Close PIL before releasing its bitmap buffer.
        try:
            import pypdfium2
        except ImportError:
            return self._read_scanned_page_pymupdf(path, index, image_agent)

        pdf = pypdfium2.PdfDocument(str(path))
        page = bitmap = image = None
        try:
            page = pdf[index]
            width, height = page.get_size()
            if not all(math.isfinite(value) and value > 0 for value in (width, height)):
                raise ValueError("Invalid PDF page dimensions")
            scale = min(
                2.0,
                self.MAX_RENDER_SIDE / max(width, height),
                math.sqrt(self.MAX_RENDER_PIXELS / (width * height)),
            )
            bitmap = page.render(scale=scale)
            image = bitmap.to_pil()
            if image.width * image.height > self.MAX_RENDER_PIXELS or max(image.size) > self.MAX_RENDER_SIDE:
                raise ValueError("PDF render exceeds pixel budget")
            with tempfile.TemporaryDirectory(prefix="career-pdf-") as temporary:
                output = Path(temporary) / f"page-{index + 1}.png"
                image.save(output, format="PNG")
                result = image_agent.perceive(
                    str(output),
                    user_goal="提取本页可见的职业规划相关文字和表格；保留原文，不补充或推测缺失事实",
                )
                if result.confidence <= 0:
                    raise ValueError("Image perception did not succeed")
                return result.raw_output or "\n".join(result.facts)
        finally:
            for resource in (image, bitmap, page, pdf):
                if resource is not None:
                    resource.close()

    def _read_scanned_page_pymupdf(self, path: Path, index: int, image_agent) -> str:
        """Use an existing optional PyMuPDF renderer when PDFium is absent."""
        import fitz

        document = fitz.open(str(path))
        try:
            page = document[index]
            width, height = page.rect.width, page.rect.height
            if not all(math.isfinite(value) and value > 0 for value in (width, height)):
                raise ValueError("Invalid PDF page dimensions")
            scale = min(2.0, self.MAX_RENDER_SIDE / max(width, height),
                        math.sqrt(self.MAX_RENDER_PIXELS / (width * height)))
            pixmap = page.get_pixmap(matrix=fitz.Matrix(scale, scale), colorspace=fitz.csRGB, alpha=False)
            if pixmap.width * pixmap.height > self.MAX_RENDER_PIXELS or max(pixmap.width, pixmap.height) > self.MAX_RENDER_SIDE:
                raise ValueError("PDF render exceeds pixel budget")
            with tempfile.TemporaryDirectory(prefix="career-pdf-") as temporary:
                output = Path(temporary) / f"page-{index + 1}.png"
                pixmap.save(str(output))
                result = image_agent.perceive(
                    str(output),
                    user_goal="提取本页可见的职业规划相关文字和表格；保留原文，不补充或推测缺失事实",
                )
                if result.confidence <= 0:
                    raise ValueError("Image perception did not succeed")
                return result.raw_output or "\n".join(result.facts)
        finally:
            document.close()

    def _read_docx(self, path: Path) -> _DocumentContent:
        import docx
        from docx.oxml.ns import qn
        from docx.table import Table
        from docx.text.paragraph import Paragraph

        document = docx.Document(str(path))
        content = _DocumentContent()
        paragraph_number = table_number = used_chars = 0

        def cell_text(cell, depth=0):
            lines = []
            for child in cell._tc.iterchildren():
                if child.tag == qn("w:p"):
                    text = Paragraph(child, cell).text.strip()
                    if text:
                        lines.append(text)
                elif child.tag == qn("w:tbl"):
                    if depth >= 4:
                        content.warnings.append("DOCX nested tables truncated at depth 4")
                        continue
                    for row in Table(child, cell).rows:
                        lines.append(" | ".join(cell_text(item, depth + 1) for item in row.cells))
            return " / ".join(lines)

        # Body children preserve the order of paragraphs and tables.
        for child in document.element.body.iterchildren():
            if child.tag == qn("w:p"):
                paragraph_number += 1
                text = Paragraph(child, document).text.strip()
                if text:
                    content.blocks.append((f"{path}#paragraph={paragraph_number}", "", text))
                    used_chars += len(text)
            elif child.tag == qn("w:tbl"):
                table_number += 1
                for number, row in enumerate(Table(child, document).rows, start=1):
                    values = [cell_text(cell) for cell in row.cells]
                    text = " | ".join(values).strip()
                    if text.strip(" |"):
                        content.blocks.append((
                            f"{path}#table={table_number}&row={number}",
                            f"[table {table_number} row {number}]", text,
                        ))
                        used_chars += len(text)
                    if used_chars > self.max_text_chars:
                        break
            if used_chars > self.max_text_chars:
                break
        return content

    def _read_xlsx(self, path: Path) -> _DocumentContent:
        import openpyxl

        content = _DocumentContent()
        workbook = openpyxl.load_workbook(str(path), data_only=True, read_only=True)
        try:
            if len(workbook.worksheets) > self.MAX_SHEETS:
                content.warnings.append(f"XLSX truncated: only the first {self.MAX_SHEETS} sheets were read")
            for sheet in workbook.worksheets[:self.MAX_SHEETS]:
                if sheet.max_row and sheet.max_row > self.MAX_ROWS:
                    content.warnings.append(f"XLSX sheet {sheet.title}: rows truncated at {self.MAX_ROWS}")
                if sheet.max_column and sheet.max_column > self.MAX_COLUMNS:
                    content.warnings.append(f"XLSX sheet {sheet.title}: columns truncated at {self.MAX_COLUMNS}")
                # Bound iteration before reading rows, including sparse sheets.
                for number, row in enumerate(sheet.iter_rows(
                    max_row=self.MAX_ROWS, max_col=self.MAX_COLUMNS, values_only=True,
                ), start=1):
                    values = [str(value) if value is not None else "" for value in row]
                    while values and not values[-1]:
                        values.pop()
                    text = " | ".join(values)
                    if text.strip(" |"):
                        content.blocks.append((
                            f"{path}#sheet={sheet.title}&row={number}",
                            f"[sheet {sheet.title} row {number}]", text,
                        ))
        finally:
            workbook.close()
        return content

    @staticmethod
    def _failure(path: Path, summary: str, reason: str) -> PerceptionResult:
        return PerceptionResult(
            modality="document", summary=summary, facts=[], evidence=[],
            confidence=0.0, missing_info=[reason], raw_output="",
        )

    def perceive(self, document_path: str, *, image_agent=None) -> PerceptionResult:
        path = Path(document_path)
        if not path.is_file():
            return self._failure(path, f"Document not found: {path.name}", "Please check document path")
        suffix = path.suffix.lower()
        readers = {
            ".txt": self._read_txt, ".md": self._read_txt,
            ".csv": self._read_txt, ".tsv": self._read_txt,
            ".docx": self._read_docx, ".xlsx": self._read_xlsx,
        }
        if suffix not in readers and suffix != ".pdf":
            return self._failure(path, f"Unsupported document format: {suffix}", f"Document format {suffix} is not supported")
        try:
            if path.stat().st_size > self.MAX_FILE_BYTES:
                return self._failure(path, f"Document too large: {path.name}", "Document exceeds the 25 MiB parsing budget")
            content = self._read_pdf(path, image_agent=image_agent) if suffix == ".pdf" else readers[suffix](path)
        except Exception as exc:
            # Do not turn private exception messages into perceived facts.
            return self._failure(path, f"Failed to parse {path.name}", f"Document parsing failed ({type(exc).__name__})")

        blocks, evidence, retained = [], [], []
        remaining = self.max_text_chars
        for source, label, text in content.blocks:
            prefix = f"{label}\n" if label else ""
            separator = "\n" if blocks else ""
            block = separator + prefix + text
            piece = block[:remaining]
            blocks.append(piece)
            retained_text = piece[len(separator) + len(prefix):]
            if retained_text.strip():
                retained.append(retained_text)
                evidence.append(EvidenceItem(source=source, quote=retained_text[:300]))
            remaining -= len(piece)
            if len(piece) < len(block):
                content.warnings.append(f"Document text truncated at {self.max_text_chars} characters; supply relevant excerpts separately")
                break
        raw = "".join(blocks)
        facts = _extract_facts_fallback("\n".join(retained), limit=8)
        if not facts:
            content.warnings.append("Document has insufficient extractable information")
        return PerceptionResult(
            modality="document", summary=f"Parsed {path.name}", facts=facts,
            evidence=evidence, confidence=_safe_confidence(0.6) if facts else 0.0,
            missing_info=list(dict.fromkeys(content.warnings)), raw_output=raw,
            requires_confirmation=content.requires_confirmation,
        )
